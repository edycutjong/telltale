#!/usr/bin/env bash
# Reproduce the whole P1c bench on the QNX guest (QEMU TCG) and regenerate evidence/RESULTS.md from the raw rows.
#   scripts/bench_all.sh run       run B1, B2, B3, B6, B7e, B4 in order (about 4.5 h on an Apple-silicon Mac under TCG)
#   scripts/bench_all.sh report    only re-analyse the committed rows -> evidence/RESULTS.md (seconds, host only)
# Needs: the guest booted and deployed (scripts/run_qemu.sh, scripts/guest_screen.sh "" any, scripts/deploy.sh) and a CLEAN
# build/ tree (every row carries the git SHA of the code that ran). Raw rows are appended to evidence/*.csv and the run
# resumes where it stopped (delete the CSV to start over). Thresholds come from scripts/target/telltale.conf, frozen by
# scripts/calibrate.py on evidence/calibration/cal1-none BEFORE any fault run.
set -euo pipefail
cd "$(dirname "$0")/.."
B="python3 scripts/bench_run.py"
report() {
  {
    echo "# Telltale bench results (generated by scripts/bench_all.sh report; do not hand-edit)"
    echo
    echo "All timing is **QEMU (TCG) timing on an x86_64 QNX 8.0 guest, not hardware timing**. Each row names the git SHA of the code that ran."
    if [ -f evidence/bench-faults.csv ] && [ -f evidence/bench-clean.csv ]; then
      echo; echo "## Measured p95 detection vs the targets fixed before the runs"; echo
      python3 scripts/targets_table.py || true
    fi
    for f in "B1 evidence/bench-faults.csv faults" "B6 evidence/bench-crash.csv faults" "B7e evidence/bench-misdraw.csv faults"; do
      set -- $f
      [ -f "$2" ] || continue
      echo; echo "## $1 — $2"; echo
      python3 scripts/bench.py "$3" "$2" --strict || true
    done
    if [ -f evidence/bench-period.csv ]; then
      echo; echo "## B4 period sweep (FREEZE x 50 per period) — evidence/bench-period.csv (10 and 50 ms); the 20 ms point is the B1 FREEZE rows, same 50 injections, not a second run"; echo
      for p in 10 20 50; do
        echo "### period_ms=$p"; echo
        python3 - "$p" <<'PY'
import csv, sys, io
sys.path.insert(0, "scripts"); import bench
src = "evidence/bench-faults.csv" if sys.argv[1] == "20" else "evidence/bench-period.csv"   # 20 ms = B1's FREEZE rows
rows = [r for r in csv.DictReader(l for l in open(src) if not l.startswith("#")) if r["period_ms"] == sys.argv[1] and r["class"] == "FREEZE"]
if rows: print(bench.render_faults(bench.analyze_faults(rows), False))
PY
      done
    fi
    echo; echo "## What a renderer self-report cannot see (BLANK, MISDRAW)"; echo
    python3 scripts/selfreport_table.py || true
    [ -f evidence/bench-ablation.csv ] && { echo; echo "## B2 ablation (monitor off) — evidence/bench-ablation.csv"; echo; python3 scripts/bench.py ablation evidence/bench-ablation.csv; }
    [ -f evidence/bench-clean.csv ] && { echo; echo "## B3 clean run (false positives) + B5 read-back cost — evidence/bench-clean.csv"; echo; python3 scripts/bench.py clean evidence/bench-clean.csv; }
  } > evidence/RESULTS.md
  echo "wrote evidence/RESULTS.md"
}
case "${1:-report}" in
  report) report ;;
  run)
    $B faults --n 50 --tag b1 --out evidence/bench-faults.csv --evroot evidence/bench-runs/b1
    $B ablation --n 10 --tag b2 --out evidence/bench-ablation.csv --evroot evidence/bench-runs/b2
    $B clean --seconds 1800 --tag b3 --out evidence/bench-clean.csv
    $B faults --n 50 --classes CRASH --tag b6 --out evidence/bench-crash.csv --evroot evidence/bench-runs/b6
    $B faults --n 10 --classes MISDRAW --tag b7e --out evidence/bench-misdraw.csv --evroot evidence/bench-runs/b7e
    for p in 10 50; do   # the 20 ms point is B1's FREEZE x 50 (same configuration), not re-run
      $B faults --n 50 --classes FREEZE --tag b4p$p --conf-extra "period_ms=$p" --out evidence/bench-period.csv --evroot evidence/bench-runs/b4-$p
    done
    report ;;
  *) echo "usage: $0 run|report" >&2; exit 1 ;;
esac
