#!/usr/bin/env bash
# Reproduce the whole P1c bench on the QNX guest (QEMU TCG) and regenerate the tables and plots from the raw rows.
#   scripts/bench_all.sh run       run B1, B2, B3, B6, B7e, B4 in order (about 4.5 h on an Apple-silicon Mac under TCG) into a
#                                  FRESH directory evidence/rerun-<UTC stamp>/ (same file names as evidence/), then report it
#   scripts/bench_all.sh report    only re-analyse the committed rows -> evidence/RESULTS.md + evidence/report.html (seconds,
#                                  host only; CI Stage 5 runs this and fails on any byte of difference)
#   TT_BENCH_OUT=<dir> scripts/bench_all.sh run|report    resume a re-run in <dir> / report <dir> (-> <dir>/RESULTS.md, report.html)
# A re-run never appends to the committed evidence/*.csv: bench_run.py skips run ids already present in its --out file (the
# file is its resume state), so pointing it at the committed rows would silently keep them instead of measuring again.
# Needs: the guest booted and deployed (scripts/run_qemu.sh, scripts/guest_screen.sh "" any, scripts/deploy.sh) and a CLEAN
# build/ tree (every row carries the git SHA of the code that ran). Thresholds come from scripts/target/telltale.conf, frozen
# by scripts/calibrate.py on evidence/calibration/cal1-none BEFORE any fault run.
set -euo pipefail
cd "$(dirname "$0")/.."
B="python3 scripts/bench_run.py"
report() {
  EV=${TT_BENCH_OUT:-evidence}; EV=${EV%/}
  export TT_EVIDENCE=$EV          # read by targets_table.py, selfreport_table.py, bench_report.py and the B4 block below
  {
    echo "# Telltale bench results (generated by scripts/bench_all.sh report; do not hand-edit)"
    echo
    echo "All timing is **QEMU (TCG) timing on an x86_64 QNX 8.0 guest, not hardware timing**. Each row names the git SHA of the code that ran."
    if [ -f "$EV/bench-faults.csv" ] && [ -f "$EV/bench-clean.csv" ]; then
      echo; echo "## Measured p95 detection vs the targets fixed before the runs"; echo
      python3 scripts/targets_table.py || true
    fi
    for f in "B1 $EV/bench-faults.csv faults" "B6 $EV/bench-crash.csv faults" "B7e $EV/bench-misdraw.csv faults"; do
      set -- $f
      [ -f "$2" ] || continue
      echo; echo "## $1 — $2"; echo
      python3 scripts/bench.py "$3" "$2" --strict || true
    done
    if [ -f "$EV/bench-period.csv" ]; then
      echo; echo "## B4 period sweep (FREEZE x 50 per period) — $EV/bench-period.csv (10 and 50 ms); the 20 ms point is the B1 FREEZE rows, same 50 injections, not a second run"; echo
      for p in 10 20 50; do
        echo "### period_ms=$p"; echo
        python3 - "$p" <<'PY'
import csv, os, sys, io
sys.path.insert(0, "scripts"); import bench
ev = os.environ["TT_EVIDENCE"]
src = f"{ev}/bench-faults.csv" if sys.argv[1] == "20" else f"{ev}/bench-period.csv"   # 20 ms = B1's FREEZE rows
rows = [r for r in csv.DictReader(l for l in open(src) if not l.startswith("#")) if r["period_ms"] == sys.argv[1] and r["class"] == "FREEZE"]
if rows: print(bench.render_faults(bench.analyze_faults(rows), False))
PY
      done
    fi
    echo; echo "## What a renderer self-report cannot see (BLANK, MISDRAW)"; echo
    python3 scripts/selfreport_table.py || true
    [ -f "$EV/bench-ablation.csv" ] && { echo; echo "## B2 ablation (monitor off) — $EV/bench-ablation.csv"; echo; python3 scripts/bench.py ablation "$EV/bench-ablation.csv"; }
    [ -f "$EV/bench-clean.csv" ] && { echo; echo "## B3 clean run (false positives) + B5 read-back cost — $EV/bench-clean.csv"; echo; python3 scripts/bench.py clean "$EV/bench-clean.csv"; }
  } > "$EV/RESULTS.md"
  echo "wrote $EV/RESULTS.md"
  python3 scripts/bench_report.py --out "$EV/report.html"
}
case "${1:-report}" in
  report) report ;;
  run)
    O=${TT_BENCH_OUT:-evidence/rerun-$(date -u +%Y%m%dT%H%M%SZ)}; O=${O%/}
    mkdir -p "$O"
    [ "$(cd "$O" && pwd -P)" != "$(cd evidence && pwd -P)" ] \
      || { echo "bench_all.sh: TT_BENCH_OUT=$O would append to the committed rows; use a new directory" >&2; exit 1; }
    echo "re-run -> $O (resume: TT_BENCH_OUT=$O $0 run)"
    $B faults --n 50 --tag b1 --out "$O/bench-faults.csv" --evroot "$O/bench-runs/b1"
    $B ablation --n 10 --tag b2 --out "$O/bench-ablation.csv" --evroot "$O/bench-runs/b2"
    $B clean --seconds 1800 --tag b3 --out "$O/bench-clean.csv" --evroot "$O/bench-runs/b3"
    $B faults --n 50 --classes CRASH --tag b6 --out "$O/bench-crash.csv" --evroot "$O/bench-runs/b6"
    $B faults --n 10 --classes MISDRAW --tag b7e --out "$O/bench-misdraw.csv" --evroot "$O/bench-runs/b7e"
    for p in 10 50; do   # the 20 ms point is B1's FREEZE x 50 (same configuration), not re-run
      $B faults --n 50 --classes FREEZE --tag b4p$p --conf-extra "period_ms=$p" --out "$O/bench-period.csv" --evroot "$O/bench-runs/b4-$p"
    done
    TT_BENCH_OUT=$O report ;;
  *) echo "usage: $0 run|report" >&2; exit 1 ;;
esac
