#!/usr/bin/env python3
"""Generate the anti-aliased text atlases the monitor uses for the fault banner and the incident card.

    python3 tools/gen_text.py [--check]

Input : third_party/d-din/D-DIN-Bold.otf (Datto, SIL OFL 1.1) -- the same face as the speed digits.
Output: src/common/textfont.h -- two sizes (banner 32 px, card 22 px), printable ASCII 32..126 plus the
        middle dot U+00B7 at index 95. Each glyph is a 4-bit coverage map stored one hex character per pixel.

Text is never decoded by the monitor (only the speed digits and lamps are), so anti-aliasing is fine here.
--check regenerates in memory and exits 1 if the committed header differs.
"""
import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "third_party/d-din/D-DIN-Bold.otf"
OUT = ROOT / "src/common/textfont.h"
SIZES = (("banner", 32), ("card", 22))
CHARS = [chr(c) for c in range(32, 127)] + ["·"]


def render_font(name, size):
    font = ImageFont.truetype(str(FONT), size)
    asc, desc = font.getmetrics()
    h = asc + desc
    adv, xo, ws, offs, data = [], [], [], [], []
    pos = 0
    for c in CHARS:
        a = round(font.getlength(c))
        x0, _, x1, _ = font.getbbox(c) if c != " " else (0, 0, 0, 0)
        w = max(0, x1 - x0)
        img = Image.new("L", (max(w, 1), h), 0)
        ImageDraw.Draw(img).text((-x0, 0), c, font=font, fill=255)
        cov = "".join("%x" % (img.getpixel((x, y)) * 15 // 255) for y in range(h) for x in range(w))
        adv.append(a)
        xo.append(x0)
        ws.append(w)
        offs.append(pos)
        data.append(cov)
        pos += len(cov)
    return name, size, h, asc, adv, xo, ws, offs, "".join(data)


def header():
    font_sha = hashlib.sha256(FONT.read_bytes()).hexdigest()
    fonts = [render_font(n, s) for n, s in SIZES]
    out = ["/* GENERATED by tools/gen_text.py -- do not edit.",
           " * font: third_party/d-din/D-DIN-Bold.otf sha256 %s (SIL OFL 1.1)" % font_sha]
    for f in fonts:
        out.append(" * %s: %d px, line height %d, coverage sha256 %s" % (f[0], f[1], f[2], hashlib.sha256(f[8].encode()).hexdigest()))
    out += [" * glyphs: ASCII 32..126, index 95 = U+00B7 middle dot; 4-bit coverage, one hex char per pixel, row-major",
            " * SPDX-License-Identifier: Apache-2.0 (generator output; glyph shapes from the OFL font above) */",
            "#ifndef TELLTALE_TEXTFONT_H", "#define TELLTALE_TEXTFONT_H", "#include \"text.h\"", ""]
    for name, size, h, asc, adv, xo, ws, offs, data in fonts:
        out.append("static const unsigned char tf_%s_adv[TT_FONT_N] = {%s};" % (name, ",".join(map(str, adv))))
        out.append("static const signed char tf_%s_xo[TT_FONT_N] = {%s};" % (name, ",".join(map(str, xo))))
        out.append("static const unsigned char tf_%s_w[TT_FONT_N] = {%s};" % (name, ",".join(map(str, ws))))
        out.append("static const unsigned tf_%s_off[TT_FONT_N] = {%s};" % (name, ",".join(map(str, offs))))
        out.append("static const char tf_%s_data[] =" % name)
        for i in range(0, len(data), 160):
            out.append("  \"%s\"" % data[i:i + 160])
        out.append("  ;")
        out.append("const struct tt_font tt_font_%s = {%d, %d, tf_%s_adv, tf_%s_xo, tf_%s_w, tf_%s_off, tf_%s_data};"
                   % (name, h, asc, name, name, name, name, name))
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    text = header()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print("textfont.h is stale: run python3 tools/gen_text.py", file=sys.stderr)
            return 1
        print("textfont.h up to date")
        return 0
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT), len(text), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
