#!/usr/bin/env python3
"""Generate the 1-bit speed-digit atlas shared by the cluster renderer and the telltale monitor.

    python3 tools/gen_glyphs.py [--check]

Input : third_party/d-din/D-DIN-Bold.otf (Datto, SIL OFL 1.1; licence beside it)
Output: src/common/glyphs.h  -- 12 glyphs (0-9, dash, blank), GLYPH_W x GLYPH_H bits each, MSB first.

The renderer blits these bits as lit/glass pixels; the monitor binarises the read-back cell and takes the
Hamming distance to every glyph. Same bits on both sides, so a correct frame decodes at distance 0.
The header records the font SHA-256, the atlas SHA-256 and the minimum pairwise Hamming distance; the
provisional decode threshold GLYPH_H_MAX_DEFAULT is a quarter of that minimum (calibrated later).
--check regenerates in memory and exits 1 if the committed header differs.
"""
import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "third_party/d-din/D-DIN-Bold.otf"
OUT = ROOT / "src/common/glyphs.h"
W, H = 150, 200          # cell size (px); digits are 200 px tall (legibility rule), D-DIN Bold needs ~146 px width
SIZE = 277               # font size giving a 200-px ink height for the tallest digit
CHARS = "0123456789-"    # index 10 = dash, index 11 = blank (all zero)


def render():
    font = ImageFont.truetype(str(FONT), SIZE)
    top = min(font.getbbox(c)[1] for c in "0123456789")
    glyphs = []
    for c in CHARS:
        x0, _, x1, _ = font.getbbox(c)
        img = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(img)
        d.text(((W - (x1 - x0)) // 2 - x0, -top), c, font=font, fill=255)
        glyphs.append([[1 if img.getpixel((x, y)) >= 128 else 0 for x in range(W)] for y in range(H)])
    glyphs.append([[0] * W for _ in range(H)])
    return glyphs


def pack(g):
    out = bytearray()
    for row in g:
        for b in range(0, W, 8):
            byte = 0
            for k in range(8):
                byte = (byte << 1) | (row[b + k] if b + k < W else 0)
            out.append(byte)
    return bytes(out)


def hamming(a, b):
    return sum(x != y for ra, rb in zip(a, b) for x, y in zip(ra, rb))


def header(glyphs):
    packed = [pack(g) for g in glyphs]
    atlas = b"".join(packed)
    dmin = min(hamming(glyphs[i], glyphs[j]) for i in range(len(glyphs)) for j in range(i + 1, len(glyphs)))
    font_sha = hashlib.sha256(FONT.read_bytes()).hexdigest()
    lines = [
        "/* GENERATED by tools/gen_glyphs.py -- do not edit.",
        f" * font: third_party/d-din/D-DIN-Bold.otf sha256 {font_sha} (SIL OFL 1.1), size {SIZE}",
        f" * atlas sha256 {hashlib.sha256(atlas).hexdigest()}",
        f" * min pairwise Hamming distance {dmin} px; provisional h_max = min/4",
        " * SPDX-License-Identifier: Apache-2.0 (generator output; glyph shapes from the OFL font above) */",
        "#ifndef TELLTALE_GLYPHS_H",
        "#define TELLTALE_GLYPHS_H",
        "#include <stdint.h>",
        f"#define GLYPH_W {W}",
        f"#define GLYPH_H {H}",
        f"#define GLYPH_ROW_BYTES {(W + 7) // 8}",
        f"#define GLYPH_N {len(glyphs)}",
        "#define GLYPH_DASH 10",
        "#define GLYPH_BLANK 11",
        f"#define GLYPH_MIN_HAMMING {dmin}",
        f"#define GLYPH_H_MAX_DEFAULT {dmin // 4}",
        "static const uint8_t glyph_bits[GLYPH_N][GLYPH_H * GLYPH_ROW_BYTES] = {",
    ]
    for i, p in enumerate(packed):
        lines.append(f"  /* {CHARS[i] if i < len(CHARS) else 'blank'} */ {{")
        for k in range(0, len(p), 24):
            lines.append("    " + ",".join(f"0x{b:02x}" for b in p[k:k + 24]) + ",")
        lines.append("  },")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main():
    text = header(render())
    if "--check" in sys.argv:
        same = OUT.exists() and OUT.read_text() == text
        print("glyphs.h up to date" if same else "glyphs.h differs from generator output")
        return 0 if same else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}", text.splitlines()[3].strip(" *"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
